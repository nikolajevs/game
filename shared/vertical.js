// Вертикаль: прыжок, падение и стояние на валунах. Общий код — сервер считает по нему настоящую высоту
// игрока, браузер предсказывает свою, поэтому оба получают одно и то же.
// z — высота ног над землёй, vz — вертикальная скорость (вверх — плюс).
import { JUMP } from './config.js';

// Гравитация подобрана так, чтобы прыжок с ровной земли длился ровно JUMP.time секунд и взлетал на JUMP.height
export const GRAVITY = (8 * JUMP.height) / (JUMP.time * JUMP.time);
export const JUMP_SPEED = (GRAVITY * JUMP.time) / 2;
// Над валуном можно пройти, если ноги не ниже его верха минус этот запас (иначе валун не пускает, как раньше)
export const PLAT_MARGIN = 2;
// Нажатие прыжка чуть раньше приземления не пропадает: ждёт, пока можно оттолкнуться
export const JUMP_BUFFER = 0.15;

// Высота площадки целого или надкушенного узла: убывает вместе с прочностью, как сам камень на экране
// (в statics3d.addRock: 0.55 + 0.45 · hp/maxHp). 0 — на узел не запрыгнуть.
export function platformTop(def, hp, maxHp) {
  return def?.climb ? def.climb.top * (0.55 + 0.45 * (hp / Math.max(1, maxHp))) : 0;
}

// Один шаг вертикали. s = { z, vz }; surf — высота опоры под ногами сейчас (0 — земля).
// Возвращает 'land', если на этом шаге приземлились, и '' в остальных случаях.
export function stepVertical(s, surf, dt) {
  if (s.z <= surf + 0.01 && s.vz <= 0) {
    // стоим на опоре (или опора только что поднялась под ноги)
    s.z = surf;
    s.vz = 0;
    return '';
  }
  // точная кинематика на шаге (а не «сначала скорость, потом путь»): иначе при 30 шагах в секунду
  // прыжок выходил заметно ниже и короче расчётного
  s.z += s.vz * dt - 0.5 * GRAVITY * dt * dt;
  s.vz -= GRAVITY * dt;
  if (s.z <= surf && s.vz <= 0) {
    s.z = surf;
    s.vz = 0;
    return 'land';
  }
  return '';
}

// В воздухе ли: ноги выше опоры или ещё летят вверх
export const airborne = (s, surf) => s.z > surf + 0.01 || s.vz > 0;
